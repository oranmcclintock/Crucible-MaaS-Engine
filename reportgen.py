"""
reportgen.py
============
Standalone Air-Gapped HTML Schema Audit Generator (v2.0).
Compiles profile.json and dbt assets into a zero-dependency, single-file HTML report.
Prints cleanly to PDF via @media print stylesheet rules.
Zero external CDN dependencies (completely air-gapped).
"""
from __future__ import annotations

import json
import os
import re
import sys
from typing import Any

import yaml
from jinja2 import Environment, FileSystemLoader, select_autoescape

import codegen

DEFAULT_BRANDING: dict[str, str | None] = {
    "brand_name": "Crucible Audit",
    "brand_color": "#0F172A",
    "brand_logo": None,
    "brand_footer": "Generated by Crucible Audit — Read-Only Air-Gapped Pre-Migration Profiler",
}

_HEX_COLOR_RE = re.compile(r"^#[0-9A-Fa-f]{3}([0-9A-Fa-f]{3})?\Z")
_LOGO_URI_RE = re.compile(
    r"^(?:https?://|data:image/(?:png|jpeg|jpg|webp|svg\+xml);base64,)"
)


def _resolve_templates_dir() -> str:
    """Resolve templates directory across source checkout, installed package, and CWD."""
    candidates = [
        os.path.join(os.path.dirname(os.path.abspath(__file__)), "templates"),
        os.path.join(sys.prefix, "share", "crucible-audit", "templates"),
        os.path.join(os.getcwd(), "templates"),
    ]
    for candidate in candidates:
        if os.path.isdir(candidate):
            return candidate
    raise FileNotFoundError(
        f"Could not locate Crucible templates directory. Checked: {', '.join(candidates)}"
    )


def resolve_branding(
    brand_config_path: str | None = None,
    brand_name: str | None = None,
    brand_color: str | None = None,
    brand_logo: str | None = None,
    brand_footer: str | None = None,
) -> dict[str, str | None]:
    """Resolve white-label branding from defaults, optional YAML/JSON config, and CLI overrides."""
    branding: dict[str, str | None] = dict(DEFAULT_BRANDING)

    if brand_config_path is not None:
        with open(brand_config_path, encoding="utf-8") as f:
            if brand_config_path.lower().endswith(".json"):
                loaded = json.load(f)
            else:
                loaded = yaml.safe_load(f)

        if isinstance(loaded, dict):
            source = (
                loaded["branding"]
                if isinstance(loaded.get("branding"), dict)
                else loaded
            )
            for key in ("brand_name", "brand_color", "brand_logo", "brand_footer"):
                short_key = key.removeprefix("brand_")
                if key in source and source[key] is not None:
                    branding[key] = source[key]
                elif short_key in source and source[short_key] is not None:
                    branding[key] = source[short_key]

    # CLI overrides take precedence over config file values
    if brand_name is not None:
        branding["brand_name"] = brand_name
    if brand_color is not None:
        branding["brand_color"] = brand_color
    if brand_logo is not None:
        branding["brand_logo"] = brand_logo
    if brand_footer is not None:
        branding["brand_footer"] = brand_footer

    # Validate brand_color strictly to prevent CSS injection
    color = branding.get("brand_color")
    if not isinstance(color, str) or not _HEX_COLOR_RE.match(color):
        raise ValueError(
            f"Invalid brand_color {color!r}: must be a 3- or 6-digit hex color (e.g. #0F172A)."
        )

    # Validate brand_logo strictly to prevent javascript: / unsafe URI injection
    logo = branding.get("brand_logo")
    if logo is not None and (not isinstance(logo, str) or not _LOGO_URI_RE.match(logo)):
        raise ValueError(
            "Invalid brand_logo: must start with https://, http://, or "
            "data:image/(png|jpeg|jpg|webp|svg+xml);base64,"
        )

    return branding


def generate_dossier(
    profile: dict[str, Any],
    output_html_path: str,
    dbt_dir: str | None = None,
    branding: dict[str, Any] | None = None,
) -> str:
    """Renders the executive readiness dossier to a standalone, zero-dependency HTML file."""
    if branding is None:
        resolved_branding = resolve_branding()
    else:
        resolved_branding = resolve_branding(
            brand_name=branding.get("brand_name"),
            brand_color=branding.get("brand_color"),
            brand_logo=branding.get("brand_logo"),
            brand_footer=branding.get("brand_footer"),
        )

    templates_dir = _resolve_templates_dir()
    html_env = Environment(
        loader=FileSystemLoader(templates_dir),
        autoescape=select_autoescape(["html", "xml", "html.j2"]),
    )
    sql_env = Environment(
        loader=FileSystemLoader(templates_dir),
        autoescape=False,
    )

    # Retrieve or generate dbt models for Section 5
    dbt_models: dict[str, str] = {}
    for table_name, tprofile in profile.get("tables", {}).items():
        model_path = (
            os.path.join(dbt_dir, "models", "staging", f"stg_{table_name}.sql")
            if dbt_dir
            else None
        )
        if model_path and os.path.exists(model_path):
            with open(model_path, encoding="utf-8") as mf:
                dbt_models[table_name] = mf.read()
        else:
            # Dynamically generate staging SQL using unescaped SQL environment
            dbt_models[table_name] = codegen.generate_dbt_staging_sql(
                table_name, tprofile, sql_env
            )

    template = html_env.get_template("readiness_dossier.html.j2")
    rendered_html = template.render(
        metadata=profile.get("metadata", {}),
        executive_summary=profile.get("executive_summary", {}),
        topology=profile.get("topology", {}),
        tables=profile.get("tables", {}),
        dbt_models=dbt_models,
        branding=resolved_branding,
    )

    out_dir = os.path.dirname(os.path.abspath(output_html_path))
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)

    with open(output_html_path, "w", encoding="utf-8") as f:
        f.write(rendered_html)

    return output_html_path


def generate_report(
    profile_path: str = "profile.json",
    out_path: str = "migration_readiness_report.html",
    dbt_dir: str | None = None,
    branding: dict[str, Any] | None = None,
) -> str:
    """Loads profile.json from disk and renders the executive readiness dossier."""
    with open(profile_path, encoding="utf-8") as f:
        profile_data = json.load(f)

    return generate_dossier(
        profile=profile_data,
        output_html_path=out_path,
        dbt_dir=dbt_dir,
        branding=branding,
    )


if __name__ == "__main__":
    prof = sys.argv[1] if len(sys.argv) > 1 else "profile.json"
    out = sys.argv[2] if len(sys.argv) > 2 else "migration_readiness_report.html"
    dbt = sys.argv[3] if len(sys.argv) > 3 else "generated_dbt"
    res = generate_report(prof, out, dbt)
    print(f"Executive dossier successfully compiled to: {res}")
